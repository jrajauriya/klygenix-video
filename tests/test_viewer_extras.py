import httpx

from harness import BASE, check, creator, finish, flush_counters, ok, premium, settled, signup, sql, upload

print("\n== Feed cards carry viewer state")
c = creator()
long_v = settled(c, upload(c, "azure-apim-auth", "Extras long video", tags=["azure", "api"])["id"])
reel = settled(c, upload(c, "reel-chai", "Extras reel")["id"])
handle = c.get("/api/video/studio/channel").json()["channel"]["handle"]
viewer = signup("Extras viewer")
check("follow", viewer.post(f"/api/video/channels/{handle}/follow").status_code, 200)
check("like", viewer.post(f"/api/video/videos/{reel['public_id']}/like").status_code, 200)
cards = viewer.get(f"/api/video/channels/{handle}/videos").json()
reels = viewer.get("/api/video/feed/reels", params={"limit": 30}).json()
mine = next((r for r in reels if r["id"] == reel["public_id"]), None)
ok("reel is in the reels feed", mine is not None)
if mine:
    check("reel card says liked", mine.get("liked"), True)
    check("reel card says following", mine.get("following"), True)
    ok("reel card has a comment count", isinstance(mine.get("comments"), int))
    ok("reel card lists caption languages", "en" in mine.get("captions", {}).get("available", []))
anon = httpx.get(f"{BASE}/api/video/feed/reels", params={"limit": 30}).json()
ok("anonymous cards are never liked", all(r.get("liked") is False for r in anon))

print("\n== Related videos")
other = settled(c, upload(c, "dal-tadka", "Extras second long", tags=["azure"])["id"])
rel = httpx.get(f"{BASE}/api/video/videos/{long_v['public_id']}/related").json()
ids = [r["id"] for r in rel]
ok("related excludes the video itself", long_v["public_id"] not in ids)
ok("related includes the same channel's long video", other["public_id"] in ids)
ok("related keeps to the same kind", all(r["kind"] == "long" for r in rel))
check("related of a missing video is 404", httpx.get(f"{BASE}/api/video/videos/zzzzzzzzzzz/related").status_code, 404)

print("\n== Search paging")
r1 = httpx.get(f"{BASE}/api/video/search", params={"q": "azure", "limit": 1})
total = int(r1.headers.get("x-total-count", "0"))
ok("search reports a total", total >= 1 and r1.json()["total"] == total)
if total > 1:
    r2 = httpx.get(f"{BASE}/api/video/search", params={"q": "azure", "limit": 1, "offset": 1}).json()
    ok("second page differs", r2["results"] and r2["results"][0]["id"] != r1.json()["results"][0]["id"])

print("\n== History")
for v in (long_v, reel):
    viewer.post(f"/api/video/videos/{v['public_id']}/progress", json={"position_ms": 1500, "completed": False})
r = viewer.get("/api/video/me/history")
check("history total", r.headers.get("x-total-count"), "2")
check("forget one", viewer.delete(f"/api/video/me/history/{reel['public_id']}").status_code, 204)
check("one left", len(viewer.get("/api/video/me/history").json()), 1)
check("clear all", viewer.delete("/api/video/me/history").status_code, 204)
check("history empty", viewer.get("/api/video/me/history").json(), [])

print("\n== Comment authors")
r = c.post(f"/api/video/videos/{long_v['public_id']}/comments", json={"body": "Creator here, thanks"})
check("creator comments", r.status_code, 201)
ok("creator comment is badged", r.json()["is_creator"] is True and r.json()["author_channel"]["handle"] == handle)
viewer.post(f"/api/video/videos/{long_v['public_id']}/comments", json={"body": "Great explainer"})
rows = httpx.get(f"{BASE}/api/video/videos/{long_v['public_id']}/comments").json()
fan = next(x for x in rows if x["body"] == "Great explainer")
ok("viewer without a channel has no author channel", fan["author_channel"] is None and fan["is_creator"] is False)

print("\n== Studio list, detail and inbox")
lst = c.get("/api/video/studio/videos").json()
ok("list rows carry suggestion_count", all("suggestion_count" in x for x in lst))
det = c.get(f"/api/video/studio/videos/{long_v['id']}").json()
ok("detail lists captions with sources", "en" in det["captions"]["available"] and det["captions"]["sources"])
viewer.post(f"/api/video/videos/{long_v['public_id']}/danmaku", json={"t_ms": 1000, "text": "inbox line"})
inbox = c.get("/api/video/studio/comments")
ok("comment inbox has both comments", sum(1 for x in inbox.json() if x["video_public_id"] == long_v["public_id"]) >= 2)
ok("inbox names the video", inbox.json()[0]["video_title"])
dm = c.get("/api/video/studio/comments", params={"kind": "danmaku"}).json()
ok("danmaku inbox names the author", any(x["body"] == "inbox line" and x["author"] == "Extras viewer" for x in dm))
outsider = creator("Extras outsider")
ok("another creator's inbox does not see them",
   all(x["video_public_id"] != long_v["public_id"] for x in outsider.get("/api/video/studio/comments").json()))

fan_row = next(x for x in c.get("/api/video/studio/comments").json() if x["body"] == "Great explainer")
check("creator hides a comment", c.patch(f"/api/video/studio/comments/{fan_row['id']}", json={"status": "hidden"}).status_code, 200)
ok("hidden comment leaves the public list", all(x["body"] != "Great explainer" for x in httpx.get(f"{BASE}/api/video/videos/{long_v['public_id']}/comments").json()))
ok("hidden filter shows it", any(x["id"] == fan_row["id"] for x in c.get("/api/video/studio/comments", params={"status": "hidden"}).json()))
check("another creator cannot unhide it", outsider.patch(f"/api/video/studio/comments/{fan_row['id']}", json={"status": "visible"}).status_code, 404)
check("creator unhides it", c.patch(f"/api/video/studio/comments/{fan_row['id']}", json={"status": "visible"}).status_code, 200)
check("bad status refused", c.patch(f"/api/video/studio/comments/{fan_row['id']}", json={"status": "deleted"}).status_code, 422)

print("\n== Analytics")
viewer.post(f"/api/video/videos/{long_v['public_id']}/progress", json={"position_ms": 9000, "watched_ms": 9000, "started": True, "completed": True})
flush_counters()
a = c.get("/api/video/studio/analytics")
check("channel analytics", a.status_code, 200)
body = a.json()
check("28 days by default", len(body["days"]), 28)
ok("totals count the videos", body["totals"]["videos"] >= 3)
ok("followers gained in the period", body["period"]["followers_gained"] >= 1)
va = c.get(f"/api/video/studio/videos/{long_v['id']}/analytics").json()
ok("per-video series", len(va["days"]) == 28 and "completion_rate" in va["totals"])
check("someone else's video analytics is 404", outsider.get(f"/api/video/studio/videos/{long_v['id']}/analytics").status_code, 404)
check("a window over a year is refused", c.get("/api/video/studio/analytics", params={"from": "2024-01-01", "to": "2026-01-01"}).status_code, 400)
days = sql("select coalesce(sum(likes),0) from kv_social.view_daily where video_id=:v", v=reel["id"])[0][0]
ok("the like rolled into view_daily", days >= 1)

print("\n== Push tokens")
tok = "ExponentPushToken[extras-suite-" + viewer.email.split("@")[0] + "]"
check("save token", viewer.post("/api/video/devices/push-token", json={"token": tok, "platform": "ios"}).status_code, 200)
check("save again is idempotent", viewer.post("/api/video/devices/push-token", json={"token": tok, "platform": "ios"}).status_code, 200)
check("one row", sql("select count(*) from kv_social.device_tokens where token=:t", t=tok)[0][0], 1)
check("bad platform refused", viewer.post("/api/video/devices/push-token", json={"token": tok, "platform": "pager"}).status_code, 422)
check("forget token", viewer.post("/api/video/devices/push-token/forget", json={"token": tok}).status_code, 200)
check("row gone", sql("select count(*) from kv_social.device_tokens where token=:t", t=tok)[0][0], 0)

print("\n== Data export and erasure")
ex = viewer.post("/api/video/me/export")
check("export", ex.status_code, 200)
data = ex.json()
check("export has the email", data["account"]["email"], viewer.email)
ok("export has the comments", any(x["body"] == "Great explainer" for x in data["comments"]))
ok("export is an attachment", "attachment" in ex.headers.get("content-disposition", ""))
paid = signup("Extras premium")
premium(paid)
check("erase refused while a paid plan renews", paid.request("DELETE", "/api/video/me", json={"confirm": "DELETE"}).status_code, 409)
check("erase needs DELETE typed", viewer.request("DELETE", "/api/video/me", json={"confirm": "yes"}).status_code, 400)
uid = viewer.user["id"]
check("erase", viewer.request("DELETE", "/api/video/me", json={"confirm": "DELETE"}).status_code, 204)
row = sql("select email, is_active, password_hash from kv_admin.users where id=:u", u=uid)[0]
ok("email scrubbed", row[0].endswith("@erased.invalid"))
check("account inactive", row[1], False)
check("password gone", row[2], None)
check("their comments are gone", sql("select count(*) from kv_social.comments where user_id=:u and status <> 'deleted'", u=uid)[0][0], 0)
check("their likes are gone", sql("select count(*) from kv_social.likes where user_id=:u", u=uid)[0][0], 0)
check("the old token stops working", viewer.get("/api/video/me").status_code, 401)
ok("the audit trail has the erasure", sql("select count(*) from kv_admin.audit_log where action='data.erase' and target_id=:u", u=uid)[0][0] == 1)

finish()
