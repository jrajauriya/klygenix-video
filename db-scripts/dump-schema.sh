#!/usr/bin/env bash
# Regenerate 01-schema.sql (and 02-reference-data.sql) from an Alembic-built database.
#
# Alembic is the only schema path (Pay's rule 13); these files are its snapshot, so a
# fresh database can be made by refresh-db.sh without Python. tests/test_migration_parity.py
# builds one database each way and diffs columns and constraints — run it after this.
set -euo pipefail
CONTAINER_NAME="klygenix-video-postgres"
PG_USER="klygenix_video"
PG_DB="klygenix_video"
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCHEMAS=(kv_admin kv_media kv_social kv_ai kv_studio kv_commerce kv_ledger kv_tax kv_trust)
ARGS=(); for s in "${SCHEMAS[@]}"; do ARGS+=(-n "$s"); done

{
  echo "-- Klygenix Play schema — generated by db-scripts/dump-schema.sh from 'alembic upgrade head'."
  echo "-- Do not edit by hand: change a model, write a migration, then regenerate."
  echo "DO \$\$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'klygenix_video_app') THEN"
  echo "  CREATE ROLE klygenix_video_app LOGIN PASSWORD 'klygenix_video_app'; END IF; END \$\$;"
  echo "CREATE EXTENSION IF NOT EXISTS vector;"
  echo "CREATE EXTENSION IF NOT EXISTS pg_trgm;"
  docker exec "$CONTAINER_NAME" pg_dump -U "$PG_USER" -d "$PG_DB" --schema-only --no-owner "${ARGS[@]}" \
    --exclude-table='kv_ai.reco_impressions_p*' --exclude-table='kv_admin.activity_log_p*' \
    | grep -v -e '^SET transaction_timeout' -e '^\\restrict' -e '^\\unrestrict'
  docker exec "$CONTAINER_NAME" pg_dump -U "$PG_USER" -d "$PG_DB" --schema-only --no-owner -t public.alembic_version
} > "$DIR/01-schema.sql"

{
  echo "-- Reference data every database carries: GST codes with dated rates and the plans."
  docker exec "$CONTAINER_NAME" pg_dump -U "$PG_USER" -d "$PG_DB" --data-only --no-owner \
    -t kv_tax.tax_codes -t kv_tax.tax_rates -t kv_tax.withholding_rates -t kv_commerce.plans \
    | grep -v -e '^SET transaction_timeout' -e '^\\restrict' -e '^\\unrestrict'
} > "$DIR/02-reference-data.sql"

# pg_dump 17 wraps its output in psql-only \restrict / \unrestrict lines; the files must
# also load through a plain driver (the parity test does), so drop them.
sed -i.bak -e '/^\\restrict /d' -e '/^\\unrestrict /d' "$DIR/01-schema.sql" "$DIR/02-reference-data.sql" && rm -f "$DIR"/*.bak

echo "Wrote 01-schema.sql ($(grep -c 'CREATE TABLE' "$DIR/01-schema.sql") tables) and 02-reference-data.sql"
